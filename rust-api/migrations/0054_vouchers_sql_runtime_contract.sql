CREATE TABLE vouchers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL CHECK (kind IN ('balance','discount')),
  amount BIGINT NOT NULL DEFAULT 0 CHECK (amount >= 0),
  discount_type TEXT CHECK (discount_type IN ('percentage','fixed')),
  discount_value BIGINT,
  max_uses BIGINT NOT NULL DEFAULT 1 CHECK (max_uses >= 1),
  used_count BIGINT NOT NULL DEFAULT 0 CHECK (used_count >= 0 AND used_count <= max_uses),
  min_purchase BIGINT NOT NULL DEFAULT 0 CHECK (min_purchase >= 0),
  max_discount BIGINT NOT NULL DEFAULT 0 CHECK (max_discount >= 0),
  one_per_user BOOLEAN NOT NULL DEFAULT TRUE,
  starts_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  product_ids UUID[] NOT NULL DEFAULT '{}',
  category_ids UUID[] NOT NULL DEFAULT '{}',
  operator_ids UUID[] NOT NULL DEFAULT '{}',
  redeemed_by_users UUID[] NOT NULL DEFAULT '{}',
  is_archived BOOLEAN NOT NULL DEFAULT FALSE,
  is_redeemed BOOLEAN NOT NULL DEFAULT FALSE,
  redeemed_at TIMESTAMPTZ,
  redeemed_by UUID REFERENCES users(id) ON DELETE SET NULL,
  redeemed_balance_before BIGINT,
  redeemed_balance_after BIGINT,
  created_by UUID REFERENCES users(id) ON DELETE SET NULL,
  archived_by UUID REFERENCES users(id) ON DELETE SET NULL,
  archive_reason TEXT,
  archived_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (kind <> 'discount' OR (discount_type IS NOT NULL AND discount_value > 0))
);
CREATE INDEX vouchers_discount_active_idx ON vouchers (code) WHERE kind='discount' AND NOT is_archived;
