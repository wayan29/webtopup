 ADD COLUMN icon TEXT NOT NULL DEFAULT '',
 ADD COLUMN instruction_image TEXT NOT NULL DEFAULT '',
 ADD COLUMN check_username BOOLEAN NOT NULL DEFAULT false,
 ADD COLUMN username_label TEXT NOT NULL DEFAULT '',
