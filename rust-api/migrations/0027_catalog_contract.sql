CREATE TABLE product_types (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 type_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 category_id UUID NOT NULL REFERENCES categories(id),
 operator_id UUID NOT NULL REFERENCES operators(id),
 name TEXT NOT NULL, slug TEXT NOT NULL,
 icon TEXT NOT NULL DEFAULT '', cover TEXT NOT NULL DEFAULT '',
 open_time TEXT NOT NULL DEFAULT '00:00', close_time TEXT NOT NULL DEFAULT '23:59',
 open_24_hours BOOLEAN NOT NULL DEFAULT true,
 estimated_delivery TEXT NOT NULL DEFAULT '', process_type TEXT NOT NULL DEFAULT 'auto',
 description TEXT NOT NULL DEFAULT '',
 popup_info JSONB NOT NULL DEFAULT '{"title":"","content":"","image":"","buttonText":"","buttonLink":"","enabled":false}',
 sort_order BIGINT NOT NULL DEFAULT 0, status BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(operator_id,slug)
);
ALTER TABLE products ALTER COLUMN operator_id DROP NOT NULL;
ALTER TABLE products
 ADD COLUMN category_id UUID REFERENCES categories(id),
 ADD COLUMN product_type_id UUID REFERENCES product_types(id),
 ADD COLUMN category TEXT NOT NULL DEFAULT '',
 ADD COLUMN brand TEXT NOT NULL DEFAULT '',
 ADD COLUMN payment_type TEXT NOT NULL DEFAULT 'prabayar' CHECK(payment_type IN ('prabayar','pascabayar')),
 ADD COLUMN icon TEXT,
 ADD COLUMN reward_points BIGINT NOT NULL DEFAULT 0,
 ADD COLUMN cost_price NUMERIC NOT NULL DEFAULT 0,
 ADD COLUMN vendor_name TEXT NOT NULL DEFAULT '',
 ADD COLUMN vendor_sku TEXT NOT NULL DEFAULT '',
 ADD COLUMN sort_order BIGINT NOT NULL DEFAULT 0,
 ADD COLUMN status BOOLEAN NOT NULL DEFAULT true,
 ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
UPDATE products p SET category_id=o.category_id, brand=o.name, category=c.name FROM operators o JOIN categories c ON c.id=o.category_id WHERE p.operator_id=o.id;
CREATE INDEX products_category_idx ON products(category_id);
CREATE INDEX products_operator_idx ON products(operator_id);
CREATE INDEX products_type_idx ON products(product_type_id);
CREATE INDEX operators_order_idx ON operators(category_id,sort_order,name);
CREATE INDEX product_types_order_idx ON product_types(operator_id,sort_order,name);
CREATE INDEX products_legacy_category_idx ON products(category) WHERE category_id IS NULL;
CREATE INDEX products_legacy_brand_idx ON products(brand) WHERE operator_id IS NULL;
CREATE VIEW catalog_categories AS SELECT c.*,
 jsonb_build_object('_id',c.id::text,'categoryId',c.category_id,'name',c.name,'slug',c.slug,'icon',c.icon,'sortOrder',c.sort_order,'status',c.status,'isActive',c.is_active,'createdAt',c.created_at,'updatedAt',c.updated_at) AS document,
 jsonb_build_object('_id',c.id::text,'name',c.name,'slug',c.slug,'icon',c.icon,'status',c.status,'isActive',c.is_active) AS brief,
 (SELECT count(*) FROM products p WHERE p.category_id=c.id) AS direct_count,
 (SELECT count(*) FROM products p WHERE p.category_id IS NULL AND p.category=c.name) AS legacy_count,
 (SELECT count(*) FROM operators o WHERE o.category_id=c.id) AS operator_count,
 (SELECT count(*) FROM product_types t WHERE t.category_id=c.id) AS type_count
 FROM categories c;
CREATE VIEW catalog_operators AS SELECT o.*,
 jsonb_build_object('_id',o.id::text,'operatorId',o.operator_id,'name',o.name,'slug',o.slug,'categoryId',o.category_id::text,'icon',o.icon,'instructionImage',o.instruction_image,'checkUsername',o.check_username,'usernameLabel',o.username_label,'validationType',o.validation_type,'description',o.description,'isCustomProduct',o.is_custom_product,'userIdLabel',o.user_id_label,'userIdType',o.user_id_type,'hasServerId',o.has_server_id,'serverIdLabel',o.server_id_label,'serverIdDropdown',o.server_id_dropdown,'serverIdType',o.server_id_type,'serverOptions',o.server_options,'sortOrder',o.sort_order,'status',o.status,'createdAt',o.created_at,'updatedAt',o.updated_at,'__v',0) AS document,
 jsonb_build_object('_id',o.id::text,'name',o.name,'slug',o.slug,'icon',o.icon,'status',o.status) AS brief,
 c.brief AS category_brief, c.name AS category_name, (c.status OR c.is_active) AS category_visible,
 (SELECT count(*) FROM products p WHERE p.operator_id=o.id) AS direct_count,
 (SELECT count(*) FROM products p WHERE p.operator_id IS NULL AND p.brand=o.name AND (p.category_id=o.category_id OR p.category=c.name)) AS legacy_count,
 (SELECT count(*) FROM product_types t WHERE t.operator_id=o.id) AS type_count
 FROM operators o JOIN catalog_categories c ON c.id=o.category_id;
CREATE VIEW catalog_product_types AS SELECT t.*,
 jsonb_build_object('_id',t.id::text,'typeId',t.type_id,'name',t.name,'slug',t.slug,'categoryId',c.brief,'operatorId',o.brief,'icon',t.icon,'cover',t.cover,'openTime',t.open_time,'closeTime',t.close_time,'open24Hours',t.open_24_hours,'estimatedDelivery',t.estimated_delivery,'processType',t.process_type,'description',t.description,'popupInfo',t.popup_info,'sortOrder',t.sort_order,'status',t.status,'createdAt',t.created_at,'updatedAt',t.updated_at,'__v',0) AS document,
 (c.status OR c.is_active) AND o.status AND o.category_visible AS parents_visible,
 (SELECT count(*) FROM products p WHERE p.product_type_id=t.id) AS product_count
 FROM product_types t JOIN catalog_categories c ON c.id=t.category_id JOIN catalog_operators o ON o.id=t.operator_id;
