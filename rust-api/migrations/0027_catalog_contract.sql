 ADD COLUMN has_server_id BOOLEAN NOT NULL DEFAULT false,
 ADD COLUMN server_id_label TEXT NOT NULL DEFAULT 'Server ID',
 ADD COLUMN server_id_dropdown BOOLEAN NOT NULL DEFAULT false,
 ADD COLUMN server_id_type TEXT NOT NULL DEFAULT 'number',
 ADD COLUMN server_options JSONB NOT NULL DEFAULT '[]',
 ADD COLUMN sort_order BIGINT NOT NULL DEFAULT 0,
